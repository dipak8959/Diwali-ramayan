#!/usr/bin/env python3
"""Write wall/vendor/fonts.js: the caption fonts (SIL Open Font License, see wall/vendor/fonts/) as data URLs, loaded with FontFace."""
import base64, os
d = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'wall', 'vendor')
faces = [('Cinzel', '600', 'normal', 'cinzel-latin-600-normal.woff2'), ('Cinzel', '700', 'normal', 'cinzel-latin-700-normal.woff2'),
         ('Cormorant Garamond', '600', 'normal', 'cormorant-garamond-latin-600-normal.woff2'), ('Cormorant Garamond', '700', 'normal', 'cormorant-garamond-latin-700-normal.woff2'),
         ('Cormorant Garamond', '600', 'italic', 'cormorant-garamond-latin-600-italic.woff2'), ('Cormorant Garamond', '700', 'italic', 'cormorant-garamond-latin-700-italic.woff2')]
out = ['// Caption fonts: Cinzel and Cormorant Garamond (SIL Open Font License 1.1, licences in vendor/fonts/). Generated by tools/make-fonts.py.',
       'window.FONTS_READY = false;', '(function () {', '  const F = [']
for fam, w, st, fn in faces:
    b = base64.b64encode(open(os.path.join(d, 'fonts', fn), 'rb').read()).decode()
    out.append("    ['%s', '%s', '%s', '%s']," % (fam, w, st, b))
out += ['  ];', '  if (!window.FontFace || !document.fonts) return;',
        "  Promise.all(F.map(([f, w, s, b]) => new FontFace(f, 'url(data:font/woff2;base64,' + b + ')', { weight: w, style: s }).load().then(x => { document.fonts.add(x); })))",
        '    .then(() => { window.FONTS_READY = true; }, () => { window.FONTS_READY = true; });', '})();']
open(os.path.join(d, 'fonts.js'), 'w').write('\n'.join(out) + '\n')
print('wrote fonts.js', os.path.getsize(os.path.join(d, 'fonts.js')) // 1024, 'KB')
